-- A setup photo for an exercise: what the box height, band anchor or hurdle spacing should look
-- like before the first rep.
--
-- The bytes live in their own table rather than on the exercise row because PUT /api/state deletes
-- and recreates every exercise of a user on each plan save (see StateService.saveState). Anything
-- stored on that row has to be re-sent by the client on every keystroke-triggered save; a UUID is
-- cheap to re-send, a few hundred kilobytes of JPEG are not. So the plan carries the reference and
-- the image keeps its own stable identity across the wipe.
--
-- The id is generated by the application, not by the database, because the upload answers with it
-- before any exercise references it.

--changeset emmaberdi:002-exercise-image splitStatements:true endDelimiter:; dbms:postgresql
--comment Per-exercise setup photo, stored as bytea and referenced by the plan.
--preconditions onFail:MARK_RAN onError:HALT
--precondition-sql-check expectedResult:0 SELECT count(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'exercise_image'

CREATE TABLE exercise_image (
    id           UUID        PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    content_type VARCHAR(32) NOT NULL,
    byte_size    INT         NOT NULL,
    width        INT         NOT NULL,
    height       INT         NOT NULL,
    data         BYTEA       NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_exercise_image_content_type CHECK (content_type IN ('image/jpeg', 'image/png'))
);

CREATE INDEX idx_exercise_image_user ON exercise_image(user_id);

-- ON DELETE SET NULL rather than CASCADE: an image going away must not take the exercise with it.
ALTER TABLE exercise
    ADD COLUMN image_id UUID REFERENCES exercise_image(id) ON DELETE SET NULL;
